#!/usr/bin/env node
// Imports incoming/listings.csv + incoming/images/ into public/images/products/
// and regenerates lib/generated-products.ts wholesale. Idempotent — safe to
// re-run any time the CSV or images change. See incoming/README.md.

import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const CSV_PATH = path.join(ROOT, "incoming", "listings.csv");
const IMAGES_DIR = path.join(ROOT, "incoming", "images");
const OUTPUT_IMAGES_DIR = path.join(ROOT, "public", "images", "products");
const GENERATED_PATH = path.join(ROOT, "lib", "generated-products.ts");

const REQUIRED_COLUMNS = ["name", "category", "price", "subcategory", "image1"];
const DEFAULT_SIZES = ["XS", "S", "M", "L", "XL"];
const PLACEHOLDER_SRC = "/images/placeholder.svg";

function parseCSV(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const next = text[i + 1];

    if (inQuotes) {
      if (char === '"' && next === '"') {
        field += '"';
        i++;
      } else if (char === '"') {
        inQuotes = false;
      } else {
        field += char;
      }
      continue;
    }

    if (char === '"') {
      inQuotes = true;
    } else if (char === ",") {
      row.push(field);
      field = "";
    } else if (char === "\n" || char === "\r") {
      if (char === "\r" && next === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += char;
    }
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((cell) => cell.trim() !== ""));
}

function slugify(name) {
  return name
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function uniqueSlug(base, used) {
  let slug = base;
  let n = 2;
  while (used.has(slug)) {
    slug = `${base}-${n}`;
    n++;
  }
  used.add(slug);
  return slug;
}

function toBool(value) {
  return String(value ?? "").trim().toLowerCase() === "yes";
}

async function processImage(filename, outputBase, warnings, rowLabel) {
  if (!filename) return null;

  const inputPath = path.join(IMAGES_DIR, filename);
  if (!fs.existsSync(inputPath)) {
    warnings.push(
      `Row "${rowLabel}": image "${filename}" not found in incoming/images/ — using placeholder.`
    );
    return PLACEHOLDER_SRC;
  }

  const outputPath = path.join(OUTPUT_IMAGES_DIR, `${outputBase}.jpg`);
  await sharp(inputPath)
    .resize({ width: 1400, withoutEnlargement: true })
    .jpeg({ quality: 85 })
    .toFile(outputPath);

  return `/images/products/${outputBase}.jpg`;
}

function serializeProducts(products) {
  const lines = products.map((p) => {
    const fields = [
      `    id: ${JSON.stringify(p.id)}`,
      `    name: ${JSON.stringify(p.name)}`,
      `    category: ${JSON.stringify(p.category)}`,
      `    subcategory: ${JSON.stringify(p.subcategory)}`,
      `    price: ${p.price}`,
    ];
    if (p.compareAtPrice != null) fields.push(`    compareAtPrice: ${p.compareAtPrice}`);
    fields.push(`    description: ${JSON.stringify(p.description)}`);
    fields.push(`    sizes: ${JSON.stringify(p.sizes)}`);
    fields.push(`    images: ${JSON.stringify(p.images)}`);
    if (p.featured) fields.push(`    featured: true`);
    if (p.isNew) fields.push(`    isNew: true`);
    if (p.trending) fields.push(`    trending: true`);
    return `  {\n${fields.join(",\n")},\n  }`;
  });

  return `// AUTO-GENERATED by scripts/import-listings.mjs — do not hand-edit.
// Edit incoming/listings.csv and run \`npm run import-listings\` instead.
import type { Product } from "./data";

export const GENERATED_PRODUCTS: Product[] = [
${lines.join(",\n")}
];
`;
}

async function main() {
  if (!fs.existsSync(CSV_PATH)) {
    console.error(
      `No incoming/listings.csv found. Copy incoming/listings-template.csv to incoming/listings.csv and fill it in first.`
    );
    process.exit(1);
  }

  fs.mkdirSync(OUTPUT_IMAGES_DIR, { recursive: true });

  const raw = fs.readFileSync(CSV_PATH, "utf8");
  const rows = parseCSV(raw);
  if (rows.length === 0) {
    console.error("incoming/listings.csv is empty.");
    process.exit(1);
  }

  const header = rows[0].map((h) => h.trim());
  const dataRows = rows.slice(1);

  const warnings = [];
  const skipped = [];
  const usedSlugs = new Set();
  const products = [];

  for (let i = 0; i < dataRows.length; i++) {
    const rowNumber = i + 2; // account for header + 1-index
    const cells = dataRows[i];
    const record = {};
    header.forEach((col, idx) => {
      record[col] = (cells[idx] ?? "").trim();
    });

    const rowLabel = record.name || `row ${rowNumber}`;

    const missing = REQUIRED_COLUMNS.filter((col) => !record[col]);
    if (missing.length > 0) {
      skipped.push(`${rowLabel}: missing required field(s) ${missing.join(", ")}`);
      continue;
    }

    if (record.category !== "women" && record.category !== "men") {
      skipped.push(`${rowLabel}: category must be "women" or "men" (got "${record.category}")`);
      continue;
    }

    const price = Number(record.price);
    if (!Number.isFinite(price) || price <= 0) {
      skipped.push(`${rowLabel}: invalid price "${record.price}"`);
      continue;
    }

    const compareAtPrice = record.compareAtPrice ? Number(record.compareAtPrice) : undefined;
    if (record.compareAtPrice && !Number.isFinite(compareAtPrice)) {
      skipped.push(`${rowLabel}: invalid compareAtPrice "${record.compareAtPrice}"`);
      continue;
    }

    const sizes = record.sizes
      ? record.sizes.split("|").map((s) => s.trim()).filter(Boolean)
      : DEFAULT_SIZES;

    const slug = uniqueSlug(slugify(record.name), usedSlugs);

    const primary = await processImage(record.image1, `${slug}-1`, warnings, rowLabel);
    const hover = record.image2
      ? await processImage(record.image2, `${slug}-2`, warnings, rowLabel)
      : primary;

    products.push({
      id: slug,
      name: record.name,
      category: record.category,
      subcategory: record.subcategory,
      price,
      compareAtPrice,
      description: record.description || "",
      sizes,
      images: [primary ?? PLACEHOLDER_SRC, hover ?? primary ?? PLACEHOLDER_SRC],
      featured: toBool(record.featured),
      isNew: toBool(record.isNew),
      trending: toBool(record.trending),
    });
  }

  fs.writeFileSync(GENERATED_PATH, serializeProducts(products));

  console.log(`Imported ${products.length} of ${dataRows.length} row(s).`);
  if (warnings.length > 0) {
    console.log(`\nWarnings (${warnings.length}):`);
    warnings.forEach((w) => console.log(`  - ${w}`));
  }
  if (skipped.length > 0) {
    console.log(`\nSkipped (${skipped.length}):`);
    skipped.forEach((s) => console.log(`  - ${s}`));
  }
  console.log(`\nWrote ${path.relative(ROOT, GENERATED_PATH)}`);
}

main().catch((err) => {
  console.error("Import failed:", err);
  process.exit(1);
});
